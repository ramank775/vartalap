/// Main country for a dial code several countries share, so typing `1`
/// picks the United States rather than the first alphabetical match.
const Map<String, String> _mainIsoForCode = {
  '1': 'US',
  '7': 'RU',
  '44': 'GB',
  '47': 'NO',
  '61': 'AU',
  '64': 'NZ',
  '212': 'MA',
  '262': 'RE',
  '500': 'FK',
  '590': 'GP',
  '672': 'NF',
};

Country? countryForIso(String? iso) {
  if (iso == null) return null;
  final upper = iso.toUpperCase();
  for (final c in kCountries) {
    if (c.iso == upper) return c;
  }
  return null;
}

/// The country a typed dial code means. [current] wins when it shares
/// the code, so picking Canada and then editing the number keeps Canada.
Country? countryForDialCode(String code, {Country? current}) {
  if (current?.dialCode == code) return current;
  final main = countryForIso(_mainIsoForCode[code]);
  if (main != null) return main;
  for (final c in kCountries) {
    if (c.dialCode == code) return c;
  }
  return null;
}
