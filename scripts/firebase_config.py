#!/usr/bin/env python3
"""Decision 209: write the Play build's Firebase config from google-services.json.

    python3 scripts/firebase_config.py <google-services.json>

Writes android/app/src/prodGms/res/values/firebase.xml, the values the
google-services Gradle plugin would generate. The plugin is not used so the
foss build stays free of Google tooling; both files stay out of git.
Prints nothing secret.
"""
import json
import pathlib
import sys
from xml.sax.saxutils import escape

PACKAGE = 'com.one9x.vartalap'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'android/app/src/prodGms/res/values/firebase.xml'

config = json.load(open(sys.argv[1]))
project = config['project_info']
client = next(c for c in config['client']
              if c['client_info']['android_client_info']['package_name'] == PACKAGE)
values = {
    'google_app_id': client['client_info']['mobilesdk_app_id'],
    'gcm_defaultSenderId': project['project_number'],
    'google_api_key': client['api_key'][0]['current_key'],
    'project_id': project['project_id'],
    'google_storage_bucket': project['storage_bucket'],
}
keep = ','.join('@string/' + name for name in values)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text('\n'.join(
    ['<?xml version="1.0" encoding="utf-8"?>',
     '<!-- Generated by scripts/firebase_config.py (decision 209). Not in git. -->',
     f'<resources xmlns:tools="http://schemas.android.com/tools" tools:keep="{keep}">']
    + [f'    <string name="{k}" translatable="false">{escape(v)}</string>' for k, v in values.items()]
    + ['</resources>', '']))
print(f'wrote {OUT.relative_to(OUT.parents[6])} for {values["project_id"]}')
